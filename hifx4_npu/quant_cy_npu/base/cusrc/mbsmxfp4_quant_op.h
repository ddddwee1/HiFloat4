        PipeBarrier<PIPE_V>();
        SetCmpMask(one_s);
        PipeBarrier<PIPE_V>();
        Select(macro_safe_s, scalar_flag, macro_safe_s, CeilDiv(valid_macros, 64), {(uint8_t)1, (uint8_t)1, (uint8_t)1, (uint8_t)8, (uint8_t)8, (uint8_t)8});
        PipeBarrier<PIPE_V>();
        Div<float, false>(macro_recip_s, six_s, macro_safe_s, MASK_PLACEHOLDER, CeilDiv(valid_macros, 64), {(uint8_t)1, (uint8_t)1, (uint8_t)1, (uint8_t)8, (uint8_t)8, (uint8_t)8});
        PipeBarrier<PIPE_V>();
        LocalTensor<uint16_t> macro_recip_u16 = macro_recip_s.ReinterpretCast<uint16_t>();

            PipeBarrier<PIPE_V>();
            SetVectorMaskByCount(32);
            PipeBarrier<PIPE_V>();
            Div<float, false>(x_float[group_col0], x_float[group_col0], group_scale_bcast, MASK_PLACEHOLDER, valid_macros, {(uint8_t)1, (uint8_t)1, (uint8_t)0, (uint8_t)16, (uint8_t)16, (uint8_t)1});
            ResetMask();
            SetVectorMaskByCount(32);
            PipeBarrier<PIPE_V>();
            Abs<float, false>(macro_abs[group_col0], x_float[group_col0], MASK_PLACEHOLDER, valid_macros, {(uint16_t)1, (uint16_t)1, (uint8_t)16, (uint8_t)16});

    LocalTensor<float> group_scale_s = AllocateLocalTensor<TPosition::VECCALC, float>(1 * 64);
    LocalTensor<float> group_exp_s = AllocateLocalTensor<TPosition::VECCALC, float>(1 * 64);
    LocalTensor<float> group_scale_bcast = AllocateLocalTensor<TPosition::VECCALC, float>(32 * 8);

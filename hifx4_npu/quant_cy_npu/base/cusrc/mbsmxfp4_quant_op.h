    LocalTensor<float> q_abs = AllocateLocalTensor<TPosition::VECCALC, float>(33 * 128);
    LocalTensor<float> neg_q_abs = AllocateLocalTensor<TPosition::VECCALC, float>(33 * 128);
    LocalTensor<float> const_full = AllocateLocalTensor<TPosition::VECCALC, float>(33 * 128);
    LocalTensor<float> macro_left_s = AllocateLocalTensor<TPosition::VECCALC, float>(1 * 64);
    LocalTensor<float> macro_right_s = AllocateLocalTensor<TPosition::VECCALC, float>(1 * 64);
    LocalTensor<float> macro_amax_s = AllocateLocalTensor<TPosition::VECCALC, float>(1 * 64);
    LocalTensor<float> macro_safe_s = AllocateLocalTensor<TPosition::VECCALC, float>(1 * 64);
    LocalTensor<float> macro_recip_s = AllocateLocalTensor<TPosition::VECCALC, float>(1 * 64);

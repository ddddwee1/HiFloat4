        LocalTensor<int> macro_recip_i32 = macro_recip_s.ReinterpretCast<int>();
        And<uint16_t, false>(macro_factor_u16, macro_recip_u16, macro_exp_mask_u16, MASK_PLACEHOLDER, CeilDiv(2 * valid_macros, 128), {(uint8_t)1, (uint8_t)1, (uint8_t)1, (uint8_t)8, (uint8_t)8, (uint8_t)8});
        PipeBarrier<PIPE_V>();
        PipeBarrier<PIPE_V>();
        Div<float, false>(macro_safe_s, macro_recip_s, macro_factor_s, MASK_PLACEHOLDER, CeilDiv(valid_macros, 64), {(uint8_t)1, (uint8_t)1, (uint8_t)1, (uint8_t)8, (uint8_t)8, (uint8_t)8});
        PipeBarrier<PIPE_V>();

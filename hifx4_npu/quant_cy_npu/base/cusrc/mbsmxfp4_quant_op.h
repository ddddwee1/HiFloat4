            PipeBarrier<PIPE_V>();
            SetCmpMask(const_full[group_col0]);
            PipeBarrier<PIPE_V>();
            Select(q_abs[group_col0], group_flag, q_abs[group_col0], valid_macros, {(uint8_t)1, (uint8_t)1, (uint8_t)1, (uint8_t)16, (uint8_t)16, (uint8_t)16});
